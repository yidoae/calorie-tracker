import { readFileSync, writeFileSync } from "node:fs";
import { callGemini } from "../../../supabase/functions/_shared/ai/gemini.ts";
import type { AiKind, FoodRef } from "../../../supabase/functions/_shared/ai/types.ts";
import { validateAnswer } from "../../../supabase/functions/_shared/ai/validate.ts";
import { loadFoods, loadPhotos, loadPhrases } from "./cases.ts";
import { formatItems, median, pct, phrasePasses, scorePlate } from "./score.ts";

/*
 * npm run eval -w aieval -- --model <id> (contracts/aieval.md): the owner's weighed photos and the
 * phrase set through the same prompt, schema and checks as the ai-log function, straight to Gemini
 * with GEMINI_API_KEY. Writes out/<model>.md: recall, false positives and weight error per photo
 * (SC-001, SC-002), phrase accuracy (SC-003, AI part), latency and cost per call. Never fails on low
 * scores: the report is the result.
 */

// Paid prices per 1M tokens (input, output), research.md §1, checked 2026-10-16.
const PRICES: Record<string, [number, number]> = {
  "gemini-3.1-flash-lite": [0.25, 1.5],
  "gemini-3.5-flash-lite": [0.3, 2.5],
  "gemini-3.6-flash": [0.75, 3.75],
  "gemini-3.8-flash": [0.75, 3.75],
};

const at = process.argv.indexOf("--model");
const model = at >= 0 ? process.argv[at + 1] : undefined;
const apiKey = process.env.GEMINI_API_KEY;
if (!model || !apiKey) {
  console.error("usage: GEMINI_API_KEY=… npm run eval -w aieval -- --model <gemini model id>");
  process.exit(2);
}

const foods = loadFoods();
const refs: FoodRef[] = foods.map((f) => ({ id: f.id, name: f.name, typicalPortionG: f.typicalPortionG }));
const byId = new Map(refs.map((f) => [f.id, f]));
const [inPrice, outPrice] = PRICES[model] ?? [Number.NaN, Number.NaN];

interface Call {
  items: { food_id: string; grams: number }[];
  ms: number;
  cost: number;
  error?: string;
}

async function run(kind: AiKind, input: string): Promise<Call> {
  const started = performance.now();
  try {
    const answer = await callGemini({ apiKey: apiKey as string, model: model as string, kind, foods: refs, input, timeoutMs: 60_000 });
    const result = validateAnswer(answer.text, byId);
    const cost = (answer.inputTokens * inPrice + answer.outputTokens * outPrice) / 1e6;
    return { items: result.items, ms: performance.now() - started, cost };
  } catch (e) {
    return { items: [], ms: performance.now() - started, cost: 0, error: e instanceof Error ? e.message : String(e) };
  }
}

const photoRows = [];
for (const c of loadPhotos(foods)) {
  const image = readFileSync(new URL(`../cases/photos/${c.file}`, import.meta.url)).toString("base64");
  const call = await run("photo", image);
  photoRows.push({ c, call, score: scorePlate(call.items, c.items) });
}
const phraseRows = [];
for (const c of loadPhrases(foods)) {
  const call = await run("text", c.text);
  phraseRows.push({ c, call, pass: phrasePasses(call.items, c.items) });
}

const calls = [...photoRows.map((r) => r.call), ...phraseRows.map((r) => r.call)];
const ms = calls.map((c) => c.ms).sort((a, b) => a - b);
const p = (q: number) => (ms.length ? ms[Math.min(ms.length - 1, Math.floor(q * ms.length))] : Number.NaN);
const sum = (xs: number[]) => xs.reduce((a, b) => a + b, 0);
const found = sum(photoRows.map((r) => r.score.found));
const expected = sum(photoRows.map((r) => r.score.expected));
const falsePos = sum(photoRows.map((r) => r.score.falsePositives));
const proposed = sum(photoRows.map((r) => r.score.proposed));

const report = [
  `# Model evaluation: ${model}`,
  "",
  `Generated by \`npm run eval -w aieval -- --model ${model}\` on ${new Date().toISOString().slice(0, 10)}; do not edit.`,
  "",
  "| Measure | Result | Bar |",
  "|---|---|---|",
  `| Photo foods found (recall) | ${expected ? pct(found / expected) : "—"} (${found}/${expected}) | ≥ 80 % (SC-001) |`,
  `| Proposed foods not on the plate | ${proposed ? pct(falsePos / proposed) : "—"} (${falsePos}/${proposed}) | < 10 % (SC-001) |`,
  `| Median weight error | ${pct(median(photoRows.flatMap((r) => r.score.weightErrors)))} | ≤ 30 % (SC-002) |`,
  `| Phrases exactly right | ${pct(phraseRows.filter((r) => r.pass).length / Math.max(1, phraseRows.length))} (${phraseRows.filter((r) => r.pass).length}/${phraseRows.length}) | ≥ 95 % (SC-003) |`,
  `| Latency p50 / p90 | ${(p(0.5) / 1000).toFixed(1)} s / ${(p(0.9) / 1000).toFixed(1)} s | p90 ≤ 8 s for photos (SC-004) |`,
  `| Cost per call (mean) | $${(sum(calls.map((c) => c.cost)) / Math.max(1, calls.length)).toFixed(5)} | — |`,
  `| Failed calls | ${calls.filter((c) => c.error).length} | — |`,
  "",
  "## Photos",
  "",
  "| Photo | Weighed | Proposed |",
  "|---|---|---|",
  ...photoRows.map((r) => `| ${r.c.id} | ${formatItems(r.c.items)} | ${r.call.error ? `error: ${r.call.error}` : formatItems(r.call.items)} |`),
  "",
  "## Phrases",
  "",
  "| | Phrase | Expected | Proposed |",
  "|---|---|---|---|",
  ...phraseRows.map((r) => `| ${r.pass ? "✓" : "✗"} | ${r.c.text} | ${formatItems(r.c.items)} | ${r.call.error ? `error: ${r.call.error}` : formatItems(r.call.items)} |`),
  "",
].join("\n");
writeFileSync(new URL(`../out/${model}.md`, import.meta.url), report);
console.log(report.split("\n").slice(4, 13).join("\n"));
