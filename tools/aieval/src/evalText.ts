import { writeFileSync } from "node:fs";
import { searchQuery } from "@calorie/core/search/normalize";
import { parseMeal } from "@calorie/core/text/parseMeal";
import { PORTION_UNITS } from "@calorie/core/text/units";
import { previewLine, proposedFoods } from "../../../apps/mobile/src/hooks/textPreviewLogic.ts";
import { loadFoods, loadPhrases } from "./cases.ts";
import { pct, phrasePasses } from "./score.ts";
import { makeSearch } from "./searchSim.ts";

/*
 * npm run eval:text -w aieval (CI): the on-device text preview, exactly as the app runs it (core
 * parser + the app's preview logic), over cases/phrases.json with the simulated food search.
 * Writes out/text.md and fails under 90 % (SC-003, preview part). No network, no key.
 */

const THRESHOLD = 0.9;
const foods = loadFoods();
const search = makeSearch(foods);
const cases = loadPhrases(foods);

const rows = cases.map((c) => {
  const lines = parseMeal(c.text, PORTION_UNITS).map((p) => previewLine(p, search(searchQuery(p.query))));
  const predicted = proposedFoods(lines).map((p) => ({ food_id: p.food.foodId, grams: p.grams }));
  return { c, predicted, pass: phrasePasses(predicted, c.items) };
});
const passed = rows.filter((r) => r.pass).length;
const share = passed / rows.length;
const fmt = (items: { food_id: string; grams: number }[]) => items.map((i) => `${i.food_id} ${i.grams} g`).join(", ") || "—";

const report = [
  "# Text preview evaluation",
  "",
  "Generated by `npm run eval:text -w aieval`; do not edit.",
  "",
  `${passed} / ${rows.length} phrases (${pct(share)}) find exactly the expected foods and grams; the bar is ${pct(THRESHOLD)} (SC-003).`,
  "",
  "| | Phrase | Expected | Preview |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.pass ? "✓" : "✗"} | ${r.c.text} | ${fmt(r.c.items)} | ${fmt(r.predicted)} |`),
  "",
].join("\n");
writeFileSync(new URL("../out/text.md", import.meta.url), report);
console.log(`text preview: ${passed}/${rows.length} (${pct(share)})`);
for (const r of rows.filter((r) => !r.pass)) console.log(`  ✗ ${r.c.text} → ${fmt(r.predicted)} (want ${fmt(r.c.items)})`);
if (share < THRESHOLD) process.exit(1);
