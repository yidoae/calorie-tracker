/*
 * supabase/tests/database/search_cases.test.sql (research.md §5, SC-002): every everyday search finds
 * its food in the top 3, and at least 95 % find it first. Queries go through core searchQuery so the
 * database sees exactly what the app sends.
 */
import { searchQuery } from "@calorie/core/search/normalize";
import type { SearchCase } from "../schemas.ts";

const str = (s: string) => `'${s.replaceAll("'", "''")}'`;

export function searchCasesSql(cases: SearchCase[]): string {
  const sorted = [...cases].sort((a, b) => a.query.localeCompare(b.query, "tr"));
  const firstNeeded = Math.ceil(sorted.length * 0.95);
  const top3 = sorted.map(
    (c) => `select ok(${str(c.expectedId)} in (select food_id from public.search_foods(${str(searchQuery(c.query))}, 3)), ${str(`"${c.query}" finds ${c.expectedId} in the top 3`)});`,
  );
  const values = sorted.map((c) => `(${str(searchQuery(c.query))}, ${str(c.expectedId)})`).join(", ");
  return `-- Generated by tools/fooddata from sources/search-cases.ts (npm run build -w fooddata); do not edit.
-- The everyday searches of SC-002 against the current food list. Nothing persists.
begin;
create extension if not exists pgtap with schema extensions;
select plan(${sorted.length + 1});

set local role authenticated;
select set_config('request.jwt.claims', json_build_object('sub', 'a5000000-0000-4000-8000-0000000000a5', 'role', 'authenticated')::text, true);

${top3.join("\n")}
select ok(
  (select count(*) from (values ${values}) as c(q, id)
    where (select food_id from public.search_foods(c.q, 1)) = c.id) >= ${firstNeeded}, '≥ 95 % of the everyday searches find the expected food first');

select * from finish();
rollback;
`;
}
