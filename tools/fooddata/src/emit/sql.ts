/*
 * The list migration (contracts/database-api.md "Food list migrations"): upserts every listed food,
 * replaces their aliases and portions, takes withdrawn foods out of search. It never deletes a food
 * and never writes meals, so saved meals keep their values (FR-010, FR-014).
 */
import type { ResolvedFood } from "../rules.ts";

const str = (s: string) => `'${s.replaceAll("'", "''")}'`;
const n2 = (x: number) => x.toFixed(2);
const n1 = (x: number) => x.toFixed(1);
const list = (ids: string[]) => `(${ids.map(str).join(", ")})`;

const COLUMNS = [
  "name_tr", "category", "kcal_per_100g", "protein_per_100g", "carbs_per_100g", "fat_per_100g",
  "alcohol_per_100g", "typical_portion_g", "source_kind", "source_ref", "searchable",
];

export function listMigrationSql(foods: ResolvedFood[], withdrawnIds: string[], label: string): string {
  const sorted = [...foods].sort((a, b) => a.id.localeCompare(b.id));
  const ids = list(sorted.map((f) => f.id));
  const rows = sorted.map((f) => {
    const v = f.per100;
    return `  (${[str(f.id), str(f.name), str(f.category), n2(v.kcal), n2(v.protein), n2(v.carbs), n2(v.fat), n2(v.alcohol), n1(f.typicalPortionG), str(f.sourceKind), str(f.sourceRef), "true"].join(", ")})`;
  });
  const aliases = sorted.flatMap((f) => [...f.aliases].sort().map((a) => `  (${str(f.id)}, ${str(a)})`));
  const portions = sorted.flatMap((f) => f.portions.map((p, i) => `  (${str(f.id)}, ${str(p.unit)}, ${n1(p.grams)}, ${i})`));

  const parts = [
    `-- Generated by tools/fooddata (npm run build -w fooddata -- --release <version>); do not edit.`,
    `-- ${label}: ${sorted.length} foods, ${aliases.length} aliases, ${portions.length} portions, ${withdrawnIds.length} withdrawn.`,
    "",
    `insert into public.foods (id, ${COLUMNS.join(", ")}) values\n${rows.join(",\n")}\non conflict (id) do update set\n${COLUMNS.map((c) => `  ${c} = excluded.${c}`).join(",\n")};`,
    "",
    `delete from public.food_aliases where food_id in ${ids};`,
    `insert into public.food_aliases (food_id, alias) values\n${aliases.join(",\n")};`,
    "",
    `delete from public.food_portions where food_id in ${ids};`,
  ];
  if (portions.length > 0) parts.push(`insert into public.food_portions (food_id, unit, grams, position) values\n${portions.join(",\n")};`);
  if (withdrawnIds.length > 0) parts.push("", `update public.foods set searchable = false where id in ${list([...withdrawnIds].sort())};`);
  return `${parts.join("\n")}\n`;
}
