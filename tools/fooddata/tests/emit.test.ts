import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { searchCasesSql } from "../src/emit/searchCases.ts";
import { listMigrationSql } from "../src/emit/sql.ts";
import type { ResolvedFood } from "../src/rules.ts";

const egg: ResolvedFood = {
  id: "egg",
  name: "Yumurta",
  category: "egg",
  sourceKind: "usda",
  sourceRef: "fdc:171287",
  per100: { kcal: 143, protein: 12.56, carbs: 0.72, fat: 9.51, alcohol: 0 },
  typicalPortionG: 50,
  portions: [{ unit: "adet", grams: 50 }],
  aliases: ["yumurta", "egg"],
};
const kofte: ResolvedFood = {
  ...egg,
  id: "kofte",
  name: "Köfte (ızgara)",
  category: "dish",
  sourceKind: "recipe",
  sourceRef: "recipe:kofte",
  per100: { kcal: 252.456, protein: 20.2, carbs: 5.8, fat: 15.8, alcohol: 0 },
  portions: [],
  aliases: ["köfte", "anne'nin köftesi"],
};

describe("list migration", () => {
  const sql = listMigrationSql([kofte, egg], ["old_food"], "release 2");

  it("upserts every column but the id, sorted by id, numbers at fixed precision", () => {
    assert.match(sql, /on conflict \(id\) do update set\n  name_tr = excluded\.name_tr,/);
    for (const col of ["category", "kcal_per_100g", "alcohol_per_100g", "typical_portion_g", "source_kind", "source_ref", "searchable"]) {
      assert.match(sql, new RegExp(`  ${col} = excluded\\.${col}`));
    }
    assert.ok(sql.indexOf("('egg'") < sql.indexOf("('kofte'"));
    assert.match(sql, /\('kofte', 'Köfte \(ızgara\)', 'dish', 252\.46, 20\.20, 5\.80, 15\.80, 0\.00, 50\.0, 'recipe', 'recipe:kofte', true\)/);
  });

  it("escapes quotes", () => {
    assert.match(sql, /'anne''nin köftesi'/);
  });

  it("replaces aliases and portions of the listed foods only", () => {
    assert.match(sql, /delete from public\.food_aliases where food_id in \('egg', 'kofte'\);/);
    assert.match(sql, /delete from public\.food_portions where food_id in \('egg', 'kofte'\);/);
    assert.match(sql, /\('egg', 'adet', 50\.0, 0\)/);
  });

  it("takes withdrawn foods out of search and never deletes foods or touches meals", () => {
    assert.match(sql, /update public\.foods set searchable = false where id in \('old_food'\);/);
    assert.doesNotMatch(sql, /delete from public\.foods/);
    assert.doesNotMatch(sql, /meal_items|public\.meals/);
  });

  it("is deterministic", () => {
    assert.equal(listMigrationSql([egg, kofte], ["old_food"], "release 2"), sql);
  });
});

describe("search cases", () => {
  const cases = [
    { query: "yumurta", expectedId: "egg" },
    { query: "köfteyi", expectedId: "kofte" },
  ];
  const sql = searchCasesSql(cases);

  it("checks each case in the top 3 and counts how many come first (SC-002)", () => {
    assert.match(sql, /select plan\(3\);/);
    assert.match(sql, /'egg' in \(select food_id from public\.search_foods\('yumurta yumur', 3\)\)/);
    assert.match(sql, />= 2, '≥ 95 % of the everyday searches find the expected food first'/);
  });

  it("sends the query the app sends: the typed words plus their stems", () => {
    assert.match(sql, /search_foods\('köfteyi köfte köftey', 3\)/);
  });

  it("runs as a signed-in user inside a rolled-back transaction", () => {
    assert.match(sql, /^-- Generated by tools\/fooddata/);
    assert.match(sql, /set local role authenticated;/);
    assert.match(sql, /rollback;\n$/);
  });
});
